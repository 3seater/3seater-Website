import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('src/batch-ten/app.js','utf8');
const start=source.indexOf('  function renderFeed(');
const filter=source.slice(start,source.indexOf('    const items = coverItems(list);',start))+'return list; }';
const config=JSON.parse(fs.readFileSync('src/site.json','utf8'));
const projects=JSON.parse(fs.readFileSync('dist/data.json','utf8')).projects;
const future={id:'future-project-test',categories:['Stage Visuals'],year:'2027',media:[]};
const context=vm.createContext({projects:[...projects,future],config,projectYears:p=>[p.year]});
vm.runInContext(filter,context);
const all=new URLSearchParams();
assert.equal(context.renderFeed(all,false).length,31);
assert.ok(!context.renderFeed(all,false).some(p=>p.id===future.id));
assert.ok(context.renderFeed(all,true).some(p=>p.id===future.id));
assert.ok(context.renderFeed(new URLSearchParams('category=Stage+Visuals&year=2027'),true).some(p=>p.id===future.id));
projects[0].title='Updated existing project';
assert.ok(context.renderFeed(all,false).some(p=>p.title==='Updated existing project'));
console.log('PASS: future projects excluded from home, included in archive/filters; existing home projects stay live.');
